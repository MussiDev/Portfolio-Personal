/**
 * Generates the 2D brain projection for mobile from the SAME .bin desktop
 * uses, so the two can never drift out of sync.
 *
 * Mobile doesn't download three.js or the 466 KB .bin (decision from
 * d3d9cb0). Until now the substitute was a generic lobed silhouette — an
 * organic drawing, not a brain. This projects the real brain in side view
 * (the same rotation as Brain3D: -90° on Y), keeps a sample of points and
 * edges, and quantizes it to Uint16: a few KB.
 *
 * The six section anchors are projected the same way, so on mobile each
 * section lands in the same brain region as on desktop.
 *
 * Usage: pnpm run brain:2d  (run after `pnpm run brain` if the model changes)
 */
import crypto from "node:crypto";
import fs from "node:fs";
import path from "node:path";

import { BIN_HEADER_SIZE, parseBinHeader, unpackVectors } from "../app/src/common/binFormat.ts";
import { BRAIN_BIN_PATH, SNAPPED_ANCHORS } from "../app/src/common/brainAsset.ts";
import { BRAIN2D_HEADER_SIZE, BRAIN2D_MAGIC } from "../app/src/common/brain2dFormat.ts";

const OUTPUT_DIR = "public/image";
const GENERATED = "app/src/common/brain2dAsset.ts";

// How many to keep. The client draws a prefix sized to the screen (the
// order is shuffled, so any prefix is an even sample).
const MAX_POINTS = 1600;
const MAX_EDGES = 2600;

const mulberry32 = (seed) => () => {
	seed = (seed + 0x6d2b79f5) | 0;
	let t = Math.imul(seed ^ (seed >>> 15), 1 | seed);
	t = (t + Math.imul(t ^ (t >>> 7), 61 | t)) ^ t;
	return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
};
const shuffle = (arr, random) => {
	for (let i = arr.length - 1; i > 0; i -= 1) {
		const j = Math.floor(random() * (i + 1));
		[arr[i], arr[j]] = [arr[j], arr[i]];
	}
	return arr;
};

const buf = fs.readFileSync(path.join("public", BRAIN_BIN_PATH));
const ab = buf.buffer.slice(buf.byteOffset, buf.byteOffset + buf.byteLength);
const { pointCount, edgeCount, min, range } = parseBinHeader(ab);
const raw = new Uint16Array(ab, BIN_HEADER_SIZE);
const pos3 = unpackVectors(raw, 0, pointCount, min, range);
const edge3 = unpackVectors(raw, pointCount * 3, edgeCount, min, range);

// Side view: -90° rotation on Y (x' = -z), and screen Y grows downward.
const project = (x, y, z) => [-z, -y];

const points = [];
for (let i = 0; i < pointCount; i += 1) {
	points.push(project(pos3[i * 3], pos3[i * 3 + 1], pos3[i * 3 + 2]));
}
const edges = [];
for (let v = 0; v + 1 < edgeCount; v += 2) {
	const a = project(edge3[v * 3], edge3[v * 3 + 1], edge3[v * 3 + 2]);
	const b = project(edge3[v * 3 + 3], edge3[v * 3 + 4], edge3[v * 3 + 5]);
	edges.push([a, b]);
}

let minX = Infinity, minY = Infinity, maxX = -Infinity, maxY = -Infinity;
for (const [x, y] of points) {
	minX = Math.min(minX, x); maxX = Math.max(maxX, x);
	minY = Math.min(minY, y); maxY = Math.max(maxY, y);
}
const width = maxX - minX;
const height = maxY - minY;
const norm = ([x, y]) => [
	Math.min(1, Math.max(0, (x - minX) / width)),
	Math.min(1, Math.max(0, (y - minY) / height)),
];

const random = mulberry32(0x2d0b);
const pointSample = shuffle(points.slice(), random).slice(0, MAX_POINTS).map(norm);
const edgeSample = shuffle(edges.slice(), random).slice(0, MAX_EDGES).map(([a, b]) => [norm(a), norm(b)]);

const q = (v) => Math.round(v * 65535);
const body = new Uint16Array(pointSample.length * 2 + edgeSample.length * 4);
let k = 0;
for (const [x, y] of pointSample) { body[k++] = q(x); body[k++] = q(y); }
for (const [[ax, ay], [bx, by]] of edgeSample) {
	body[k++] = q(ax); body[k++] = q(ay); body[k++] = q(bx); body[k++] = q(by);
}

const header = Buffer.alloc(BRAIN2D_HEADER_SIZE);
header.write(BRAIN2D_MAGIC, 0, "ascii");
header.writeUInt32LE(pointSample.length, 4);
header.writeUInt32LE(edgeSample.length, 8);
header.writeFloatLE(width / height, 12);
const file = Buffer.concat([header, Buffer.from(body.buffer)]);

const hash = crypto.createHash("sha256").update(file).digest("hex").slice(0, 10);
const filename = `brain-2d.${hash}.bin`;
for (const f of fs.readdirSync(OUTPUT_DIR)) {
	if (/^brain-2d\.[a-f0-9]+\.bin$/.test(f) && f !== filename) fs.unlinkSync(path.join(OUTPUT_DIR, f));
}
fs.writeFileSync(path.join(OUTPUT_DIR, filename), file);

const anchors = SNAPPED_ANCHORS.map(([x, y, z]) => norm(project(x, y, z)).map((v) => Number(v.toFixed(4))));
fs.writeFileSync(
	GENERATED,
	`// Generated by scripts/prepare-brain-2d.mjs — do not edit by hand.
export const BRAIN2D_PATH = "/image/${filename}";

// Section anchors (brainAsset.ts), projected to the same side view and
// normalized to [0,1] over the brain's width and height.
export const ANCHORS_2D: readonly [number, number][] = ${JSON.stringify(anchors)};
`,
);

console.log(`${filename}: ${pointSample.length} points, ${edgeSample.length} edges, ${(file.length / 1024).toFixed(1)} KB, ratio ${(width / height).toFixed(3)}`);
console.log("2D anchors:", JSON.stringify(anchors));
